-- Additive Phase 5 source migration. Synthetic diagnosis codes are not ICD codes.
CREATE TABLE public.diagnoses (
 diagnosis_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(diagnosis_id>0),
 diagnosis_code VARCHAR(32) NOT NULL UNIQUE CHECK(length(trim(diagnosis_code))>0),
 diagnosis_name VARCHAR(128) NOT NULL CHECK(length(trim(diagnosis_name))>0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK(updated_at>=created_at)
);
CREATE TABLE public.encounter_doctors (
 association_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(association_id>0),
 encounter_id BIGINT NOT NULL REFERENCES public.encounters(encounter_id),
 doctor_id BIGINT NOT NULL REFERENCES public.doctors(doctor_id),
 role VARCHAR(16) NOT NULL CHECK(role IN ('PRIMARY','CONSULTING')),
 joined_at TIMESTAMPTZ NOT NULL, left_at TIMESTAMPTZ,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK(updated_at>=created_at),
 CHECK(left_at IS NULL OR left_at>joined_at),
 UNIQUE(encounter_id,doctor_id,joined_at),
 EXCLUDE USING gist (encounter_id WITH =, tstzrange(joined_at,left_at,'[)') WITH &&)
 WHERE (role='PRIMARY' AND is_active)
);
CREATE TABLE public.encounter_diagnoses (
 association_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(association_id>0),
 encounter_id BIGINT NOT NULL REFERENCES public.encounters(encounter_id),
 diagnosis_id BIGINT NOT NULL REFERENCES public.diagnoses(diagnosis_id),
 is_primary BOOLEAN NOT NULL DEFAULT FALSE,
 recorded_at TIMESTAMPTZ NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK(updated_at>=created_at)
);
CREATE UNIQUE INDEX encounter_diagnosis_active_unique ON public.encounter_diagnoses(encounter_id,diagnosis_id) WHERE is_active;
CREATE UNIQUE INDEX encounter_diagnosis_primary_unique ON public.encounter_diagnoses(encounter_id) WHERE is_active AND is_primary;
CREATE INDEX encounter_doctors_encounter_idx ON public.encounter_doctors(encounter_id);
CREATE INDEX encounter_diagnoses_encounter_idx ON public.encounter_diagnoses(encounter_id);
CREATE FUNCTION public.guard_encounter_relation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE e public.encounters; started TIMESTAMPTZ; finished TIMESTAMPTZ;
BEGIN
 SELECT * INTO STRICT e FROM public.encounters WHERE encounter_id=NEW.encounter_id FOR KEY SHARE;
 started:=COALESCE(e.checked_in_at,e.admitted_at);
 finished:=COALESCE(e.consultation_completed_at,e.discharged_at);
 IF TG_TABLE_NAME='encounter_doctors' THEN
   IF started IS NULL OR NEW.joined_at<started OR (finished IS NOT NULL AND
       (NEW.joined_at>finished OR NEW.left_at IS NULL OR NEW.left_at>finished)) THEN
     RAISE EXCEPTION 'doctor participation outside encounter';
   END IF;
   IF NEW.is_active AND NEW.role='PRIMARY' AND NEW.doctor_id IS DISTINCT FROM e.doctor_id THEN
     RAISE EXCEPTION 'primary doctor must match encounter doctor';
   END IF;
 ELSE
   IF COALESCE(e.consultation_started_at,e.admitted_at) IS NULL OR
      NEW.recorded_at<COALESCE(e.consultation_started_at,e.admitted_at) THEN
     RAISE EXCEPTION 'diagnosis requires a started consultation/admission';
   END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER encounter_doctors_context BEFORE INSERT OR UPDATE ON public.encounter_doctors FOR EACH ROW EXECUTE FUNCTION public.guard_encounter_relation();
CREATE TRIGGER encounter_diagnoses_context BEFORE INSERT OR UPDATE ON public.encounter_diagnoses FOR EACH ROW EXECUTE FUNCTION public.guard_encounter_relation();
CREATE FUNCTION public.guard_encounter_primary_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.doctor_id IS DISTINCT FROM OLD.doctor_id AND EXISTS(
   SELECT 1 FROM public.encounter_doctors WHERE encounter_id=NEW.encounter_id
   AND role='PRIMARY' AND is_active AND doctor_id IS DISTINCT FROM NEW.doctor_id) THEN
   RAISE EXCEPTION 'update primary participation before changing encounter doctor';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER encounter_primary_change BEFORE UPDATE ON public.encounters FOR EACH ROW EXECUTE FUNCTION public.guard_encounter_primary_change();
DO $$ DECLARE t TEXT; p TEXT; BEGIN
 FOR t,p IN SELECT * FROM (VALUES('diagnoses','diagnosis_id'),('encounter_doctors','association_id'),('encounter_diagnoses','association_id')) x(t,p) LOOP
   EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.guard_source_update(%L)',t||'_update_guard',t,p);
   EXECUTE format('CREATE TRIGGER %I BEFORE DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.reject_source_delete()',t||'_no_delete',t);
   EXECUTE format('CREATE INDEX %I ON public.%I(updated_at,%I)',t||'_incremental_idx',t,p);
 END LOOP;
END $$;
