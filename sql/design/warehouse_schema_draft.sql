-- Phase 1 design draft; PostgreSQL 16+. No deployment is performed by this file.
-- Apply only to a disposable design database, before kpi_queries.sql.
-- raw/stg/ops ingestion contracts are defined in their own design files.
BEGIN;
CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS dw;
CREATE SCHEMA IF NOT EXISTS mart;
CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE dw.dim_date (
    date_key INTEGER PRIMARY KEY,
    calendar_date DATE UNIQUE,
    calendar_year SMALLINT,
    calendar_quarter SMALLINT,
    calendar_month SMALLINT,
    day_of_month SMALLINT,
    iso_day_of_week SMALLINT,
    is_weekend BOOLEAN,
    CHECK ((date_key = 0 AND calendar_date IS NULL) OR
           (calendar_date IS NOT NULL AND date_key = to_char(calendar_date, 'YYYYMMDD')::INTEGER))
);
CREATE TABLE dw.dim_patient (
    patient_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT UNIQUE CHECK (patient_id > 0),
    patient_code TEXT,
    date_of_birth DATE,
    gender TEXT,
    is_active BOOLEAN,
    source_updated_at TIMESTAMPTZ,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE dw.dim_department (
    department_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT UNIQUE CHECK (department_id > 0),
    department_code TEXT,
    department_name TEXT,
    is_active BOOLEAN,
    source_updated_at TIMESTAMPTZ,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE dw.dim_doctor (
    doctor_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id BIGINT CHECK (doctor_id > 0),
    doctor_code TEXT,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    is_active BOOLEAN,
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (doctor_id, effective_from),
    CHECK (effective_to IS NULL OR effective_to > effective_from)
);
CREATE UNIQUE INDEX uq_dim_doctor_current ON dw.dim_doctor(doctor_id)
    WHERE effective_to IS NULL AND doctor_id IS NOT NULL;
-- SCD2 overlap is additionally a pre-merge DQ assertion; no extension required.
CREATE TABLE dw.dim_bed (
    bed_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_id BIGINT UNIQUE CHECK (bed_id > 0),
    bed_code TEXT,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    bed_type TEXT,
    commissioned_at TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE dw.dim_lab_test_type (
    lab_test_type_sk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_test_type_id BIGINT UNIQUE CHECK (lab_test_type_id > 0),
    test_code TEXT,
    test_name TEXT,
    default_tat_minutes INTEGER CHECK (default_tat_minutes > 0),
    is_active BOOLEAN,
    source_updated_at TIMESTAMPTZ,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Unknown members: source BK remains NULL; SK 0 never represents a real entity.
INSERT INTO dw.dim_date(date_key) VALUES (0);
INSERT INTO dw.dim_patient(patient_sk, patient_code) VALUES (0, 'UNKNOWN');
INSERT INTO dw.dim_department(department_sk, department_code, department_name)
VALUES (0, 'UNKNOWN', 'Không xác định');
INSERT INTO dw.dim_doctor(doctor_sk, doctor_code, department_sk, effective_from)
VALUES (0, 'UNKNOWN', 0, '-infinity');
INSERT INTO dw.dim_bed(bed_sk, bed_code, department_sk) VALUES (0, 'UNKNOWN', 0);
INSERT INTO dw.dim_lab_test_type(lab_test_type_sk, test_code) VALUES (0, 'UNKNOWN');

CREATE TABLE dw.fact_appointment (
    appointment_sk BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL UNIQUE CHECK (appointment_id > 0),
    rescheduled_from_appointment_id BIGINT,
    patient_sk BIGINT NOT NULL REFERENCES dw.dim_patient,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    doctor_sk BIGINT NOT NULL REFERENCES dw.dim_doctor,
    doctor_id BIGINT,
    scheduled_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    scheduled_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    status_changed_at TIMESTAMPTZ,
    eligibility_as_of TIMESTAMPTZ NOT NULL,
    is_noshow_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    source_updated_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT is_noshow_eligible OR
           (scheduled_at IS NOT NULL AND scheduled_date_key <> 0 AND
            scheduled_at <= eligibility_as_of AND status IN ('ATTENDED', 'NO_SHOW') AND
            status_changed_at IS NOT NULL AND status_changed_at <= eligibility_as_of AND
            (status <> 'NO_SHOW' OR status_changed_at >= scheduled_at + INTERVAL '24 hours')))
);
CREATE TABLE dw.fact_outpatient_encounter (
    outpatient_encounter_sk BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL UNIQUE CHECK (encounter_id > 0),
    appointment_id BIGINT,
    patient_sk BIGINT NOT NULL REFERENCES dw.dim_patient,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    doctor_sk BIGINT NOT NULL REFERENCES dw.dim_doctor,
    doctor_id BIGINT,
    checked_in_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    consultation_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    checked_in_at TIMESTAMPTZ,
    consultation_started_at TIMESTAMPTZ,
    consultation_completed_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    is_visit_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    is_waiting_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    waiting_minutes NUMERIC GENERATED ALWAYS AS
        (CASE WHEN is_waiting_eligible THEN EXTRACT(EPOCH FROM
            (consultation_started_at - checked_in_at)) / 60.0 END) STORED,
    source_updated_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT is_visit_eligible OR (consultation_started_at IS NOT NULL AND consultation_date_key <> 0)),
    CHECK (NOT is_waiting_eligible OR (is_visit_eligible AND checked_in_at IS NOT NULL AND
           consultation_started_at >= checked_in_at))
);
CREATE TABLE dw.fact_inpatient_encounter (
    inpatient_encounter_sk BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL UNIQUE CHECK (encounter_id > 0),
    parent_encounter_id BIGINT,
    patient_sk BIGINT NOT NULL REFERENCES dw.dim_patient,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    doctor_sk BIGINT NOT NULL REFERENCES dw.dim_doctor,
    doctor_id BIGINT,
    admission_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    discharge_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    admitted_at TIMESTAMPTZ,
    discharged_at TIMESTAMPTZ,
    status TEXT NOT NULL,
    is_admission_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    is_los_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    los_days NUMERIC GENERATED ALWAYS AS
        (CASE WHEN is_los_eligible THEN EXTRACT(EPOCH FROM
            (discharged_at - admitted_at)) / 86400.0 END) STORED,
    source_updated_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT is_admission_eligible OR (admitted_at IS NOT NULL AND admission_date_key <> 0)),
    CHECK (NOT is_los_eligible OR (is_admission_eligible AND status = 'DISCHARGED' AND discharged_at IS NOT NULL AND
           discharge_date_key <> 0 AND discharged_at > admitted_at))
);
CREATE TABLE dw.fact_bed_assignment (
    bed_assignment_sk BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    bed_assignment_id BIGINT NOT NULL UNIQUE CHECK (bed_assignment_id > 0),
    encounter_id BIGINT NOT NULL CHECK (encounter_id > 0),
    patient_sk BIGINT NOT NULL REFERENCES dw.dim_patient,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    bed_sk BIGINT NOT NULL REFERENCES dw.dim_bed,
    assigned_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    released_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    assigned_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    is_assignment_valid BOOLEAN NOT NULL DEFAULT FALSE,
    source_updated_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT is_assignment_valid OR (released_at IS NULL OR released_at > assigned_at))
);
CREATE TABLE dw.fact_bed_snapshot_daily (
    bed_snapshot_sk BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    bed_sk BIGINT NOT NULL REFERENCES dw.dim_bed CHECK (bed_sk <> 0),
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    snapshot_date_key INTEGER NOT NULL REFERENCES dw.dim_date CHECK (snapshot_date_key <> 0),
    snapshot_at TIMESTAMPTZ NOT NULL,
    bed_status TEXT,
    is_active BOOLEAN NOT NULL,
    is_occupied BOOLEAN NOT NULL,
    is_snapshot_valid BOOLEAN NOT NULL,
    bed_assignment_id BIGINT,
    encounter_id BIGINT,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (bed_sk, snapshot_date_key),
    CHECK ((snapshot_at AT TIME ZONE 'Asia/Ho_Chi_Minh')::TIME = TIME '00:00:00'),
    CHECK (NOT is_snapshot_valid OR (bed_status IS NOT NULL AND bed_status IN ('ACTIVE', 'MAINTENANCE', 'INACTIVE'))),
    CHECK (NOT is_snapshot_valid OR is_active = (bed_status = 'ACTIVE')),
    CHECK (NOT is_snapshot_valid OR NOT is_occupied OR is_active)
);
CREATE TABLE dw.fact_lab_order (
    lab_order_sk BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    lab_order_id BIGINT NOT NULL UNIQUE CHECK (lab_order_id > 0),
    encounter_id BIGINT NOT NULL CHECK (encounter_id > 0),
    patient_sk BIGINT NOT NULL REFERENCES dw.dim_patient,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    doctor_sk BIGINT NOT NULL REFERENCES dw.dim_doctor,
    doctor_id BIGINT,
    lab_test_type_sk BIGINT NOT NULL REFERENCES dw.dim_lab_test_type,
    ordered_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    result_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    ordered_at TIMESTAMPTZ,
    collected_at TIMESTAMPTZ,
    processing_started_at TIMESTAMPTZ,
    result_completed_at TIMESTAMPTZ,
    target_tat_minutes_at_order INTEGER,
    status TEXT NOT NULL,
    is_completed_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    is_tat_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    is_ontime_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    tat_minutes NUMERIC GENERATED ALWAYS AS
        (CASE WHEN is_tat_eligible THEN EXTRACT(EPOCH FROM
            (result_completed_at - ordered_at)) / 60.0 END) STORED,
    source_updated_at TIMESTAMPTZ NOT NULL,
    batch_id UUID NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (NOT is_completed_eligible OR (status = 'COMPLETED' AND
           result_completed_at IS NOT NULL AND result_date_key <> 0)),
    CHECK (NOT is_tat_eligible OR (is_completed_eligible AND ordered_at IS NOT NULL AND
           result_completed_at >= ordered_at AND
           (collected_at IS NULL OR collected_at BETWEEN ordered_at AND result_completed_at) AND
           (processing_started_at IS NULL OR processing_started_at BETWEEN ordered_at AND result_completed_at) AND
           (collected_at IS NULL OR processing_started_at IS NULL OR processing_started_at >= collected_at))),
    CHECK (NOT is_ontime_eligible OR (is_tat_eligible AND target_tat_minutes_at_order IS NOT NULL AND target_tat_minutes_at_order > 0))
);
CREATE TABLE dw.fact_operational_event (
    event_id UUID PRIMARY KEY,
    topic TEXT NOT NULL CHECK (topic IN ('appointments.events', 'encounters.events', 'laboratory.events')),
    event_type TEXT NOT NULL,
    entity_id BIGINT NOT NULL CHECK (entity_id > 0),
    appointment_id BIGINT,
    encounter_id BIGINT,
    lab_order_id BIGINT,
    source_system TEXT NOT NULL,
    schema_version TEXT NOT NULL,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    event_date_key INTEGER NOT NULL REFERENCES dw.dim_date,
    event_time TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL,
    partition_id INTEGER NOT NULL CHECK (partition_id >= 0),
    kafka_offset BIGINT NOT NULL CHECK (kafka_offset >= 0),
    is_rt_eligible BOOLEAN NOT NULL DEFAULT FALSE,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((topic = 'appointments.events' AND appointment_id IS NOT NULL AND appointment_id = entity_id
            AND encounter_id IS NULL AND lab_order_id IS NULL) OR
           (topic = 'encounters.events' AND encounter_id IS NOT NULL AND encounter_id = entity_id
            AND appointment_id IS NULL AND lab_order_id IS NULL) OR
           (topic = 'laboratory.events' AND lab_order_id IS NOT NULL AND lab_order_id = entity_id
            AND encounter_id IS NOT NULL AND appointment_id IS NULL))
);
CREATE INDEX ix_event_rt ON dw.fact_operational_event(event_time, department_sk)
    WHERE is_rt_eligible;
CREATE INDEX ix_op_date_dept ON dw.fact_outpatient_encounter(consultation_date_key, department_sk);
CREATE INDEX ix_ip_admission_dept ON dw.fact_inpatient_encounter(admission_date_key, department_sk);
CREATE INDEX ix_ip_discharge_dept ON dw.fact_inpatient_encounter(discharge_date_key, department_sk);
CREATE INDEX ix_lab_result_dept ON dw.fact_lab_order(result_date_key, department_sk);

-- Preserve additive components. BI aggregates sums/counts then divides once.
CREATE VIEW mart.outpatient_daily AS
SELECT d.calendar_date AS report_date, f.department_sk,
       count(*) FILTER (WHERE f.is_visit_eligible) AS visit_count,
       count(*) FILTER (WHERE f.is_waiting_eligible) AS waiting_valid_count,
       sum(f.waiting_minutes) FILTER (WHERE f.is_waiting_eligible) AS waiting_minutes_sum
FROM dw.fact_outpatient_encounter f
JOIN dw.dim_date d ON d.date_key = f.consultation_date_key
WHERE d.calendar_date IS NOT NULL
GROUP BY d.calendar_date, f.department_sk;

CREATE VIEW mart.appointment_daily AS
SELECT d.calendar_date AS report_date, f.department_sk,
       count(*) FILTER (WHERE f.is_noshow_eligible AND f.status = 'NO_SHOW') AS no_show_count,
       count(*) FILTER (WHERE f.is_noshow_eligible) AS classified_count
FROM dw.fact_appointment f
JOIN dw.dim_date d ON d.date_key = f.scheduled_date_key
WHERE d.calendar_date IS NOT NULL
GROUP BY d.calendar_date, f.department_sk;

CREATE VIEW mart.inpatient_admission_daily AS
SELECT d.calendar_date AS report_date, f.department_sk,
       count(*) FILTER (WHERE f.is_admission_eligible) AS admission_count
FROM dw.fact_inpatient_encounter f
JOIN dw.dim_date d ON d.date_key = f.admission_date_key
WHERE d.calendar_date IS NOT NULL
GROUP BY d.calendar_date, f.department_sk;

CREATE VIEW mart.inpatient_discharge_daily AS
SELECT d.calendar_date AS report_date, f.department_sk,
       count(*) FILTER (WHERE f.is_los_eligible) AS los_valid_count,
       sum(f.los_days) FILTER (WHERE f.is_los_eligible) AS los_days_sum
FROM dw.fact_inpatient_encounter f
JOIN dw.dim_date d ON d.date_key = f.discharge_date_key
WHERE d.calendar_date IS NOT NULL
GROUP BY d.calendar_date, f.department_sk;

CREATE VIEW mart.bed_occupancy_daily AS
SELECT d.calendar_date AS report_date, f.department_sk,
       count(*) FILTER (WHERE f.is_snapshot_valid AND f.is_active) AS active_capacity,
       count(*) FILTER (WHERE f.is_snapshot_valid AND f.is_active AND f.is_occupied) AS occupied_beds,
       count(*) FILTER (WHERE NOT f.is_snapshot_valid) AS invalid_snapshot_count,
       count(*) AS commissioned_beds
FROM dw.fact_bed_snapshot_daily f
JOIN dw.dim_date d ON d.date_key = f.snapshot_date_key
GROUP BY d.calendar_date, f.department_sk;

CREATE VIEW mart.lab_daily AS
SELECT d.calendar_date AS report_date, f.department_sk,
       count(*) FILTER (WHERE f.is_completed_eligible) AS completed_orders,
       count(*) FILTER (WHERE f.is_tat_eligible) AS tat_valid_count,
       sum(f.tat_minutes) FILTER (WHERE f.is_tat_eligible) AS tat_minutes_sum,
       count(*) FILTER (WHERE f.is_ontime_eligible) AS ontime_valid_count,
       count(*) FILTER (WHERE f.is_ontime_eligible AND
                            f.tat_minutes <= f.target_tat_minutes_at_order) AS ontime_orders
FROM dw.fact_lab_order f
JOIN dw.dim_date d ON d.date_key = f.result_date_key
WHERE d.calendar_date IS NOT NULL
GROUP BY d.calendar_date, f.department_sk;

CREATE TABLE mart.realtime_department_snapshot (
    as_of TIMESTAMPTZ NOT NULL,
    department_sk BIGINT NOT NULL REFERENCES dw.dim_department,
    checkins_last_15m BIGINT NOT NULL CHECK (checkins_last_15m >= 0),
    lab_results_last_15m BIGINT NOT NULL CHECK (lab_results_last_15m >= 0),
    refreshed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (as_of, department_sk)
);
COMMIT;
