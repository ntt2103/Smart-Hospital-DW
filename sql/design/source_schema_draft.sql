-- Target: database hospital_oltp, schema public. PostgreSQL 16+.
-- Phase 2: create/connect the intended empty database first; review privileges.
-- No DROP, TRUNCATE, data migration, or service startup is performed here.
-- btree_gist is needed by the three exclusion constraints in this draft.
-- If extension installation is unavailable, do not silently remove these guards:
-- record an implementation deviation and supply serialized writer + equivalent DQ.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE public.patients (
    patient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (patient_id > 0),
    patient_code VARCHAR(32) NOT NULL UNIQUE CHECK (length(trim(patient_code)) > 0),
    date_of_birth DATE NOT NULL,
    gender VARCHAR(16) NOT NULL CHECK (gender IN ('FEMALE','MALE','OTHER','UNKNOWN')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at)
);
CREATE TABLE public.departments (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (department_id > 0),
    department_code VARCHAR(32) NOT NULL UNIQUE CHECK (length(trim(department_code)) > 0),
    department_name VARCHAR(128) NOT NULL CHECK (length(trim(department_name)) > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at)
);
CREATE TABLE public.doctors (
    doctor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (doctor_id > 0),
    doctor_code VARCHAR(32) NOT NULL UNIQUE CHECK (length(trim(doctor_code)) > 0),
    department_id BIGINT NOT NULL REFERENCES public.departments(department_id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at)
);
CREATE TABLE public.appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (appointment_id > 0),
    patient_id BIGINT NOT NULL REFERENCES public.patients(patient_id),
    department_id BIGINT NOT NULL REFERENCES public.departments(department_id),
    doctor_id BIGINT REFERENCES public.doctors(doctor_id),
    scheduled_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (status IN ('SCHEDULED','ATTENDED','NO_SHOW','CANCELLED','RESCHEDULED')),
    status_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    rescheduled_from_appointment_id BIGINT UNIQUE REFERENCES public.appointments(appointment_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at),
    CHECK (rescheduled_from_appointment_id IS NULL OR rescheduled_from_appointment_id <> appointment_id)
);
CREATE TABLE public.encounters (
    encounter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (encounter_id > 0),
    patient_id BIGINT NOT NULL REFERENCES public.patients(patient_id),
    department_id BIGINT NOT NULL REFERENCES public.departments(department_id),
    doctor_id BIGINT REFERENCES public.doctors(doctor_id),
    appointment_id BIGINT UNIQUE REFERENCES public.appointments(appointment_id),
    parent_encounter_id BIGINT UNIQUE REFERENCES public.encounters(encounter_id),
    encounter_type VARCHAR(16) NOT NULL CHECK (encounter_type IN ('OUTPATIENT','INPATIENT')),
    status VARCHAR(32) NOT NULL,
    status_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    checked_in_at TIMESTAMPTZ,
    consultation_started_at TIMESTAMPTZ,
    consultation_completed_at TIMESTAMPTZ,
    admitted_at TIMESTAMPTZ,
    discharged_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at),
    CHECK (parent_encounter_id IS NULL OR parent_encounter_id <> encounter_id),
    CHECK (consultation_started_at IS NULL OR
           (checked_in_at IS NOT NULL AND consultation_started_at >= checked_in_at)),
    CHECK (consultation_completed_at IS NULL OR
           (consultation_started_at IS NOT NULL AND consultation_completed_at >= consultation_started_at)),
    CHECK (discharged_at IS NULL OR (admitted_at IS NOT NULL AND discharged_at > admitted_at)),
    CONSTRAINT encounter_type_state CHECK (
      (encounter_type = 'OUTPATIENT' AND parent_encounter_id IS NULL
       AND admitted_at IS NULL AND discharged_at IS NULL AND (
        (status = 'REGISTERED' AND checked_in_at IS NULL AND consultation_started_at IS NULL AND consultation_completed_at IS NULL) OR
        (status = 'CHECKED_IN' AND checked_in_at IS NOT NULL AND consultation_started_at IS NULL AND consultation_completed_at IS NULL) OR
        (status = 'IN_CONSULTATION' AND checked_in_at IS NOT NULL AND consultation_started_at IS NOT NULL AND consultation_completed_at IS NULL) OR
        (status = 'COMPLETED' AND checked_in_at IS NOT NULL AND consultation_started_at IS NOT NULL AND consultation_completed_at IS NOT NULL) OR
        (status = 'CANCELLED' AND consultation_started_at IS NULL AND consultation_completed_at IS NULL)
      )) OR
      (encounter_type = 'INPATIENT' AND appointment_id IS NULL
       AND checked_in_at IS NULL AND consultation_started_at IS NULL AND consultation_completed_at IS NULL AND (
        (status = 'ADMITTED' AND admitted_at IS NOT NULL AND discharged_at IS NULL) OR
        (status = 'DISCHARGED' AND admitted_at IS NOT NULL AND discharged_at IS NOT NULL) OR
        (status = 'CANCELLED' AND admitted_at IS NULL AND discharged_at IS NULL AND parent_encounter_id IS NULL)
      ))
    )
);
CREATE TABLE public.beds (
    bed_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (bed_id > 0),
    department_id BIGINT NOT NULL REFERENCES public.departments(department_id),
    bed_code VARCHAR(32) NOT NULL UNIQUE CHECK (length(trim(bed_code)) > 0),
    bed_type VARCHAR(16) NOT NULL DEFAULT 'REGULAR' CHECK (bed_type IN ('REGULAR','ICU')),
    commissioned_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at)
);
CREATE TABLE public.bed_status_history (
    bed_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (bed_status_history_id > 0),
    bed_id BIGINT NOT NULL REFERENCES public.beds(bed_id),
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','MAINTENANCE','INACTIVE')),
    effective_from TIMESTAMPTZ NOT NULL,
    effective_to TIMESTAMPTZ,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT bed_status_no_overlap EXCLUDE USING gist
      (bed_id WITH =, tstzrange(effective_from, effective_to, '[)') WITH &&)
      DEFERRABLE INITIALLY IMMEDIATE
);
CREATE UNIQUE INDEX bed_status_one_open ON public.bed_status_history (bed_id) WHERE effective_to IS NULL;
CREATE TABLE public.bed_assignments (
    bed_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (bed_assignment_id > 0),
    bed_id BIGINT NOT NULL REFERENCES public.beds(bed_id),
    encounter_id BIGINT NOT NULL REFERENCES public.encounters(encounter_id),
    assigned_at TIMESTAMPTZ NOT NULL,
    released_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at),
    CHECK (released_at IS NULL OR released_at > assigned_at),
    CONSTRAINT bed_assignment_no_bed_overlap EXCLUDE USING gist
      (bed_id WITH =, tstzrange(assigned_at, released_at, '[)') WITH &&)
      DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT bed_assignment_no_encounter_overlap EXCLUDE USING gist
      (encounter_id WITH =, tstzrange(assigned_at, released_at, '[)') WITH &&)
      DEFERRABLE INITIALLY IMMEDIATE
);
CREATE TABLE public.lab_test_types (
    lab_test_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (lab_test_type_id > 0),
    test_code VARCHAR(32) NOT NULL UNIQUE CHECK (length(trim(test_code)) > 0),
    test_name VARCHAR(128) NOT NULL CHECK (length(trim(test_name)) > 0),
    default_tat_minutes INTEGER NOT NULL CHECK (default_tat_minutes > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at)
);
CREATE TABLE public.lab_orders (
    lab_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (lab_order_id > 0),
    encounter_id BIGINT NOT NULL REFERENCES public.encounters(encounter_id),
    department_id BIGINT NOT NULL REFERENCES public.departments(department_id),
    lab_test_type_id BIGINT NOT NULL REFERENCES public.lab_test_types(lab_test_type_id),
    status VARCHAR(16) NOT NULL DEFAULT 'ORDERED'
      CHECK (status IN ('ORDERED','COLLECTED','PROCESSING','COMPLETED','CANCELLED')),
    status_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ordered_at TIMESTAMPTZ NOT NULL,
    collected_at TIMESTAMPTZ,
    processing_started_at TIMESTAMPTZ,
    result_completed_at TIMESTAMPTZ,
    target_tat_minutes_at_order INTEGER NOT NULL CHECK (target_tat_minutes_at_order > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK (updated_at >= created_at),
    CHECK (collected_at IS NULL OR collected_at >= ordered_at),
    CHECK (processing_started_at IS NULL OR (collected_at IS NOT NULL AND processing_started_at >= collected_at)),
    CHECK (result_completed_at IS NULL OR (processing_started_at IS NOT NULL AND result_completed_at >= processing_started_at)),
    CHECK (status_changed_at >= ordered_at),
    CONSTRAINT lab_status_timeline CHECK (
      (status = 'ORDERED' AND collected_at IS NULL AND processing_started_at IS NULL AND result_completed_at IS NULL) OR
      (status = 'COLLECTED' AND collected_at IS NOT NULL AND processing_started_at IS NULL AND result_completed_at IS NULL) OR
      (status = 'PROCESSING' AND collected_at IS NOT NULL AND processing_started_at IS NOT NULL AND result_completed_at IS NULL) OR
      (status = 'COMPLETED' AND collected_at IS NOT NULL AND processing_started_at IS NOT NULL AND result_completed_at IS NOT NULL) OR
      (status = 'CANCELLED' AND result_completed_at IS NULL)
    )
);

-- Mutation guards: unchanged identity/creation/owning department; every update
-- receives a fresh extraction timestamp, including retrospective corrections.
CREATE FUNCTION public.guard_source_update() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW) -> TG_ARGV[0]) IS DISTINCT FROM (to_jsonb(OLD) -> TG_ARGV[0]) THEN
    RAISE EXCEPTION 'source primary key is immutable';
  END IF;
  IF NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'created_at is immutable';
  END IF;
  IF TG_TABLE_NAME IN ('appointments','encounters','beds','lab_orders') AND
     (to_jsonb(NEW) -> 'department_id') IS DISTINCT FROM (to_jsonb(OLD) -> 'department_id') THEN
    RAISE EXCEPTION 'owning department_id is immutable';
  END IF;
  IF TG_TABLE_NAME = 'lab_orders' AND
     (to_jsonb(NEW) -> 'target_tat_minutes_at_order') IS DISTINCT FROM (to_jsonb(OLD) -> 'target_tat_minutes_at_order') THEN
    RAISE EXCEPTION 'lab target frozen at order creation';
  END IF;
  NEW.updated_at := GREATEST(clock_timestamp(), OLD.updated_at + INTERVAL '1 microsecond');
  RETURN NEW;
END;
$$;
CREATE FUNCTION public.reject_source_delete() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'physical source DELETE forbidden: use inactive/status transitions';
END;
$$;
DO $$
DECLARE source_table TEXT; source_pk TEXT;
BEGIN
  FOR source_table, source_pk IN SELECT * FROM (VALUES
    ('patients','patient_id'),('departments','department_id'),('doctors','doctor_id'),
    ('appointments','appointment_id'),('encounters','encounter_id'),('beds','bed_id'),
    ('bed_status_history','bed_status_history_id'),('bed_assignments','bed_assignment_id'),
    ('lab_test_types','lab_test_type_id'),('lab_orders','lab_order_id')) AS items(t,p)
  LOOP
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.guard_source_update(%L)',
                   source_table || '_update_guard', source_table, source_pk);
    EXECUTE format('CREATE TRIGGER %I BEFORE DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.reject_source_delete()',
                   source_table || '_no_delete', source_table);
    EXECUTE format('CREATE INDEX %I ON public.%I (updated_at, %I)',
                   source_table || '_incremental_idx', source_table, source_pk);
  END LOOP;
END;
$$;
CREATE INDEX appointments_patient_idx ON public.appointments(patient_id);
CREATE INDEX encounters_patient_idx ON public.encounters(patient_id);
CREATE INDEX lab_orders_encounter_idx ON public.lab_orders(encounter_id);
CREATE INDEX lab_orders_result_idx ON public.lab_orders(result_completed_at) WHERE status = 'COMPLETED';
COMMIT;

