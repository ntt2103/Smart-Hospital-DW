-- Phase 1 design draft. Target hospital_dwh; apply ops_schema_draft.sql first.
-- No schema here is a production-tested migration.
BEGIN;
CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE raw.source_rows (
    raw_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id UUID NOT NULL REFERENCES ops.pipeline_runs(run_id),
    source_table TEXT NOT NULL CHECK (source_table IN (
        'patients','departments','doctors','appointments','encounters',
        'beds','bed_status_history','bed_assignments','lab_test_types','lab_orders')),
    source_pk BIGINT NOT NULL CHECK (source_pk > 0),
    source_updated_at TIMESTAMPTZ NOT NULL,
    extracted_at TIMESTAMPTZ NOT NULL,
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    UNIQUE (batch_id, source_table, source_pk)
);
CREATE INDEX raw_source_rows_latest_idx
    ON raw.source_rows(source_table, source_pk, source_updated_at DESC, raw_id DESC);

CREATE TABLE raw.events (
    event_id UUID PRIMARY KEY,
    event_type TEXT NOT NULL CHECK (event_type IN (
        'created','status_changed','checked_in','consultation_started','admitted',
        'bed_assigned','bed_released','discharged','order_created','sample_collected',
        'processing_started','result_completed','cancelled')),
    entity_id BIGINT NOT NULL CHECK (entity_id BETWEEN 1 AND 9007199254740991),
    schema_version TEXT NOT NULL CHECK (schema_version = '1.0.0'),
    event_time TIMESTAMPTZ NOT NULL,
    published_at TIMESTAMPTZ NOT NULL CHECK (published_at >= event_time),
    source_system TEXT NOT NULL CHECK (source_system = 'hospital_simulator'),
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    event_body JSONB NOT NULL CHECK (jsonb_typeof(event_body) = 'object'),
    body_sha256 CHAR(64) NOT NULL CHECK (body_sha256 ~ '^[0-9a-f]{64}$'),
    topic TEXT NOT NULL CHECK (topic IN ('appointments.events','encounters.events','laboratory.events')),
    partition_id INTEGER NOT NULL CHECK (partition_id >= 0),
    kafka_offset BIGINT NOT NULL CHECK (kafka_offset >= 0),
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CHECK (
       (topic='appointments.events' AND event_type IN ('created','status_changed')) OR
       (topic='encounters.events' AND event_type IN (
          'checked_in','consultation_started','admitted','bed_assigned','bed_released','discharged')) OR
       (topic='laboratory.events' AND event_type IN (
          'order_created','sample_collected','processing_started','result_completed','cancelled'))
    ),
    UNIQUE (topic, partition_id, kafka_offset)
);
CREATE INDEX raw_events_window_idx ON raw.events(event_type, event_time, ingested_at);

CREATE TABLE raw.event_deliveries (
    topic TEXT NOT NULL,
    partition_id INTEGER NOT NULL CHECK (partition_id >= 0),
    kafka_offset BIGINT NOT NULL CHECK (kafka_offset >= 0),
    key_text TEXT,
    raw_value BYTEA NOT NULL,
    event_body JSONB,
    claimed_event_id UUID,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    disposition TEXT NOT NULL CHECK (disposition IN ('canonical','duplicate','quarantined')),
    event_id UUID REFERENCES raw.events(event_id),
    quarantine_id BIGINT REFERENCES ops.quarantined_records(quarantine_id),
    PRIMARY KEY (topic, partition_id, kafka_offset),
    CHECK (
       (disposition IN ('canonical','duplicate') AND event_id IS NOT NULL AND quarantine_id IS NULL) OR
       (disposition='quarantined' AND event_id IS NULL AND quarantine_id IS NOT NULL)
    )
);
CREATE INDEX raw_event_delivery_claimed_id_idx ON raw.event_deliveries(claimed_event_id);
COMMENT ON TABLE raw.events IS 'One immutable valid canonical body per event_id; first valid ingestion metadata retained.';
COMMENT ON TABLE raw.event_deliveries IS 'Every Kafka receipt position, including duplicates and malformed bytes. Commit offset only after this transaction.';
COMMENT ON COLUMN raw.events.body_sha256 IS 'SHA-256 of sorted-key compact UTF-8 JSON producer body, excluding consumer metadata. Compare JSONB as well on ID conflicts.';
COMMIT;
